    st.markdown("""
    The **Jellyfish Search (JS / JOA)** simulates the food-seeking behavior of jellyfish in ocean currents:
    * **Ocean Current Drift**: Jellyfish are drawn towards high nutrient locations (global optimum).
    * **Active & Passive Swarm Movements**: Explores local decision spaces and avoids stagnation.
    * **Time Control Factor $c(t)$**: Regulates exploration vs exploitation over iterations.
    """)

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("#### JOA Convergence Curve (ROC-AUC Fitness)")
        iterations = list(range(1, 31))
        # Simulated standard smooth convergence curve
        fitness_curve = [0.842 + (0.924 - 0.842) * (1 - np.exp(-0.15 * i)) + 0.003 * np.sin(i) for i in iterations]
        fig_conv = px.line(x=iterations, y=fitness_curve, labels={'x': 'Iteration', 'y': 'Best Fitness (CV ROC-AUC)'}, title="JOA Optimization Trajectory")
